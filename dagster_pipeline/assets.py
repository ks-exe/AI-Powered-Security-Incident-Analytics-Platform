@asset(
    ins={"silver": AssetIn("silver_events")},
    description="Gold KPI summary table",
    group_name="analytics",
    metadata={
        "table": "kpi_summary",
        "layer": "gold",
    },
)
def gold_kpi_summary(context: AssetExecutionContext, silver: int) -> Output[dict]:
    """Run dbt Gold KPI model. Returns KPI values."""
    context.log.info(f"Running dbt Gold KPI model (silver has {silver} records)")

    result = subprocess.run(
        [
            "dbt", "run",
            "--select", "kpi_summary",
            "--project-dir", "dbt_project",
            "--profiles-dir", "dbt_project",
            "--target", "dev",
        ],
        capture_output=True,
        text=True,
    )

    if result.returncode != 0:
        context.log.error(f"dbt Gold KPI run failed: {result.stderr}")
        raise RuntimeError(f"dbt Gold KPI model failed: {result.stderr}")

    # Read KPI values
    import duckdb

    conn = duckdb.connect("data/security_analytics.duckdb", read_only=True)
    try:
        row = conn.execute(
            "SELECT total_attacks, failed_login_rate, avg_mttd_minutes, "
            "avg_mttr_minutes, sla_compliance FROM security_analytics.kpi_summary"
        ).fetchone()
        kpis = {
            "total_attacks": row[0] if row else 0,
            "failed_login_rate": row[1] if row else 0.0,
            "avg_mttd_minutes": row[2] if row else 0.0,
            "avg_mttr_minutes": row[3] if row else 0.0,
            "sla_compliance": row[4] if row else 0.0,
        }
    except Exception:
        kpis = {}
    finally:
        conn.close()

    context.log.info(f"Gold KPI summary computed: {kpis}")

    return Output(
        kpis,
        metadata={
            "total_attacks": MetadataValue.int(kpis.get("total_attacks", 0)),
            "failed_login_rate": MetadataValue.float(kpis.get("failed_login_rate", 0.0)),
            "avg_mttd_minutes": MetadataValue.float(kpis.get("avg_mttd_minutes", 0.0)),
            "avg_mttr_minutes": MetadataValue.float(kpis.get("avg_mttr_minutes", 0.0)),
            "sla_compliance": MetadataValue.float(kpis.get("sla_compliance", 0.0)),
        },
    )


