@asset(
    ins={"silver": AssetIn("silver_events")},
    description="Anomaly detection results from IsolationForest model",
    group_name="ml",
    metadata={
        "table": "anomaly_results",
        "layer": "gold",
        "model": "IsolationForest",
    },
)
def anomaly_results(context: AssetExecutionContext, silver: int) -> Output[int]:
    """Train model and score windows. Returns anomaly count.

    Runs the full ML pipeline: feature extraction, model training,
    prediction, and persistence of results.
    """
    context.log.info(f"Running anomaly detection pipeline (silver has {silver} records)")

    try:
        from ml_detection.features import extract_features
        from ml_detection.train import TrainingConfig, train_model
        from ml_detection.predict import persist_results, predict_anomalies

        db_path = Path("data/security_analytics.duckdb")

        # Extract features from hourly event summary
        features_df = extract_features(db_path)
        context.log.info(f"Extracted {len(features_df)} feature vectors")

        # Train model
        training_config = TrainingConfig()
        training_result = train_model(features_df, training_config)
        context.log.info(
            f"Model trained: {training_result.n_anomalies_detected} anomalies "
            f"({training_result.anomaly_percentage:.1f}%)"
        )

        # Predict anomalies
        prediction_result = predict_anomalies(features_df, training_result.model_path)
        context.log.info(
            f"Prediction complete: {prediction_result.n_anomalies} anomalies detected"
        )

        # Persist results
        rows_written = persist_results(
            prediction_result, db_path, training_result.model_version
        )

        return Output(
            prediction_result.n_anomalies,
            metadata={
                "anomalies_detected": MetadataValue.int(prediction_result.n_anomalies),
                "anomaly_percentage": MetadataValue.float(prediction_result.anomaly_percentage),
                "model_version": MetadataValue.text(training_result.model_version),
                "rows_written": MetadataValue.int(rows_written),
            },
        )

    except ImportError:
        # ML module not yet implemented - return placeholder
        context.log.warning(
            "ml_detection module not available. "
            "Anomaly detection will be available after Sprint 8."
        )
        return Output(
            0,
            metadata={
                "status": MetadataValue.text("skipped - ml_detection not implemented"),
            },
        )
    except Exception as e:
        context.log.error(f"Anomaly detection failed: {e}")
        raise
