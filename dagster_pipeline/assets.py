@asset(
    ins={"bronze": AssetIn("bronze_events")},
    description="Silver layer: cleaned, deduplicated, enriched events",
    group_name="transformation",
    metadata={
        "table": "silver_events",
        "layer": "silver",
    },
)
def silver_events(context: AssetExecutionContext, bronze: int) -> Output[int]:
    """Run dbt Silver models. Returns record count."""
    context.log.info(f"Running dbt Silver models (bronze has {bronze} records)")

    result = subprocess.run(
        [
            "dbt", "run",
            "--select", "stg_security_events silver_events",
            "--project-dir", "dbt_project",
            "--profiles-dir", "dbt_project",
            "--target", "dev",
        ],
        capture_output=True,
        text=True,
    )

    if result.returncode != 0:
        context.log.error(f"dbt Silver run failed: {result.stderr}")
        raise RuntimeError(f"dbt Silver models failed: {result.stderr}")

    context.log.info("dbt Silver models completed successfully")

    # Count silver records
    import duckdb

    conn = duckdb.connect("data/security_analytics.duckdb", read_only=True)
    try:
        row = conn.execute(
            "SELECT COUNT(*) FROM security_analytics.silver_events"
        ).fetchone()
        record_count = row[0] if row else 0
    except Exception:
        record_count = 0
    finally:
        conn.close()

    return Output(
        record_count,
        metadata={
            "record_count": MetadataValue.int(record_count),
            "dbt_output": MetadataValue.text(result.stdout[-2000:] if result.stdout else ""),
        },
    )


