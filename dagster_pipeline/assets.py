@asset(
    description="Raw security events generated by Mock Data Generator",
    group_name="ingestion",
    metadata={
        "format": "JSONL + Parquet",
        "output_dir": "mock_data/",
    },
)
def raw_security_events(context: AssetExecutionContext) -> Output[str]:
    """Generate mock security data and return path to output files."""
    from mock_data.generator import GeneratorConfig, generate_security_events, write_events

    config = GeneratorConfig(count=10_000, seed=42)
    context.log.info(f"Generating {config.count} security events with seed={config.seed}")

    events = generate_security_events(config)
    output_paths = write_events(events, config)

    output_dir = str(config.output_dir)
    context.log.info(
        f"Generated {len(events)} events to {output_dir}",
    )

    return Output(
        output_dir,
        metadata={
            "event_count": MetadataValue.int(len(events)),
            "output_dir": MetadataValue.text(output_dir),
            "formats": MetadataValue.text(", ".join(config.output_formats)),
        },
    )


@asset(
    ins={"raw_data": AssetIn("raw_security_events")},
    description="Bronze layer: raw events loaded via DLT pipeline",
    group_name="ingestion",
    metadata={
        "table": "raw_security_events",
        "layer": "bronze",
    },
)
def bronze_events(context: AssetExecutionContext, raw_data: str) -> Output[int]:
    """Run DLT ingestion pipeline. Returns record count."""
    from dlt_pipeline.pipeline import run_ingestion

    source_dir = Path(raw_data)
    context.log.info(f"Running DLT ingestion from {source_dir}")

    result = run_ingestion(source_dir=source_dir)

    context.log.info(
        f"Ingested {result.records_ingested} records, "
        f"rejected {result.records_rejected}, "
        f"batch_id={result.batch_id}"
    )

    return Output(
        result.records_ingested,
        metadata={
            "records_ingested": MetadataValue.int(result.records_ingested),
            "records_rejected": MetadataValue.int(result.records_rejected),
            "elapsed_seconds": MetadataValue.float(result.elapsed_seconds),
            "records_per_second": MetadataValue.float(result.records_per_second),
            "batch_id": MetadataValue.text(result.batch_id),
        },
    )


